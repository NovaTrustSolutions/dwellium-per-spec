/**
 * templateGeneratorStore — SSR-safe per-user store for the Template
 * Generator widget's templates (HTML source + per-key variable values/types).
 *
 * Per-USER, dynamic key `dwellium:templateGenerator:<uid>` (holder
 * `templateGeneratorUserIdHolder`, written by the perUserIdentity single
 * writer) + One Save `withSync('templateGenerator')` — universalShellStore
 * sister shape (plan 058) — so templates follow the account to any machine.
 *
 * Mirrors the established createLocalStorageStore + useSyncExternalStore
 * pattern (see universalShellStore.ts / docs/code.md 2026-09-17). Read via
 * the useTemplateGeneratorState() hook; write via setTemplateGeneratorState().
 */
import { useSyncExternalStore } from 'react';
import { createLocalStorageStore } from './createLocalStorageStore';
import { withSync } from '../lib/oneSaveStore';
import { templateGeneratorUserIdHolder, usePerUserIdentity } from '../lib/perUserIdentity';
import type { VarType } from '../components/DocViewer/templateEngine';

export interface StoredTemplate {
    id: string;
    name: string;
    html: string;
    values: Record<string, string>;
    types: Record<string, VarType>;
}

export interface TemplateGeneratorState {
    templates: StoredTemplate[];
    activeId: string;
}

/** Per-user key prefix. Full key is `${TEMPLATE_GENERATOR_KEY}:<uid>` or `:_anonymous`. */
export const TEMPLATE_GENERATOR_KEY = 'dwellium:templateGenerator';

