export function createDefaultState(): TemplateGeneratorState {
    return {
        templates: [{ id: 'default', name: 'Property report', html: DEFAULT_HTML_TEMPLATE, values: {}, types: {} }],
        activeId: 'default',
    };
}

function resolveKey(): string {
    return `${TEMPLATE_GENERATOR_KEY}:${templateGeneratorUserIdHolder.current ?? '_anonymous'}`;
}

const VAR_TYPES: readonly VarType[] = ['text', 'number', 'date', 'currency'];

function isStringRecord(v: unknown): v is Record<string, string> {
    return v != null && typeof v === 'object' && !Array.isArray(v)
        && Object.values(v as Record<string, unknown>).every((x) => typeof x === 'string');
}

function isVarTypeRecord(v: unknown): v is Record<string, VarType> {
    return v != null && typeof v === 'object' && !Array.isArray(v)
        && Object.values(v as Record<string, unknown>).every((x) => (VAR_TYPES as readonly string[]).includes(x as string));
}

/** Validates one template shape field by field — a malformed entry is dropped, not the whole list. */
function isStoredTemplate(v: unknown): v is StoredTemplate {
    if (v == null || typeof v !== 'object') return false;
    const t = v as Record<string, unknown>;
    return typeof t.id === 'string' && t.id.length > 0
        && typeof t.name === 'string'
        && typeof t.html === 'string'
        && isStringRecord(t.values)
        && isVarTypeRecord(t.types);
}

function deserialize(raw: string | null): TemplateGeneratorState {
    if (raw == null) return createDefaultState();
    try {
        const parsed = JSON.parse(raw) as { templates?: unknown; activeId?: unknown } | null;
        if (parsed == null || typeof parsed !== 'object' || !Array.isArray(parsed.templates)) return createDefaultState();
        const templates = parsed.templates.filter(isStoredTemplate);
        if (templates.length === 0) return createDefaultState();
        const activeId = typeof parsed.activeId === 'string' && templates.some((t) => t.id === parsed.activeId)
            ? parsed.activeId
            : templates[0].id;
        return { templates, activeId };
    } catch {
        return createDefaultState();
    }
}

export const templateGeneratorStore = withSync(
    createLocalStorageStore<TemplateGeneratorState>({ key: resolveKey, deserializer: deserialize, defaultValue: createDefaultState() }),
    { objectType: 'templateGenerator', holder: templateGeneratorUserIdHolder, resolveKey },
);

/** Replace the stored state and notify subscribers (caller owns merging — e.g. one template's values). */
export function setTemplateGeneratorState(next: TemplateGeneratorState): void {
    templateGeneratorStore.set(next, () => {
        try { localStorage.setItem(resolveKey(), JSON.stringify(next)); } catch { /* quota / sandboxed — keep typing */ }
    });
}

/** Read the current + subscribe to changes. SSR-safe. */
export function useTemplateGeneratorState(): TemplateGeneratorState {
    usePerUserIdentity(); // single writer — resolve this render's user.id into every holder first
    return useSyncExternalStore(
        templateGeneratorStore.subscribe,
        templateGeneratorStore.getSnapshot,
        templateGeneratorStore.getServerSnapshot,
    );
}
